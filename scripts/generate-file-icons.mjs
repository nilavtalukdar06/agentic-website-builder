import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { getIconData, iconToSVG } from "@iconify/utils";

const require = createRequire(import.meta.url);
const collection = require("@iconify-json/material-icon-theme/icons.json");

const icons = {
  react: "react-ts",
  typescript: "typescript",
  javascript: "javascript",
  css: "css",
  json: "json",
  markdown: "markdown",
  mdx: "mdx",
  html: "html",
  svg: "svg",
  image: "image",
  npm: "npm",
  tailwind: "tailwindcss",
  env: "tune",
  git: "git",
  yaml: "yaml",
  file: "document",
};

const entries = Object.entries(icons).map(([kind, name]) => {
  const data = getIconData(collection, name);
  if (!data) throw new Error(`Missing icon ${name}`);
  const { attributes, body } = iconToSVG(data);
  return `  ${kind}: { viewBox: ${JSON.stringify(attributes.viewBox)}, body: ${JSON.stringify(body)} },`;
});

const output = `// Generated by scripts/generate-file-icons.mjs from @iconify-json/material-icon-theme (MIT). Do not edit.
export const fileIconData = {
${entries.join("\n")}
} as const;

export type FileKind = keyof typeof fileIconData;
`;

writeFileSync(
  new URL("../src/components/files/file-icons.generated.ts", import.meta.url),
  output,
);
